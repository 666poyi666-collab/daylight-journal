/** Build the read-only ChatGPT review request for one journal date. */
export function buildReviewPrompt(date: string): string {
  return `请使用“拾光日记”连接器完成 ${date} 的个人日记复盘。

先调用 journal_get_entry 读取当天完整正文与写作时间；若返回的 contentComplete 为 false，必须用 nextOffset 继续调用直到读完。再调用 journal_list_recent 获取近期脉络，需要对照的日期同样用 journal_get_entry 读完正文。不要只依据列表摘要复盘，不要修改、补写或虚构任何日记。

这不是简短摘要。请根据日记证据给出一份深入、诚实、具体且温和的复盘，按以下结构输出：
1. 今日全景：发生了什么，哪些事情最重要，它们之间有什么联系。
2. 行动与选择：我做了什么、回避了什么、作出了哪些决定，分别带来了什么结果。
3. 情绪轨迹：结合各记录片和写作时间，分析情绪怎样变化；区分日记原文、合理推断和无法确定之处。
4. 做得好的地方：指出具体行为及其价值，不说空泛的鼓励。
5. 阻力与盲点：识别拖延、冲突、消耗、反复出现的问题或认知偏差，但不要做医学诊断。
6. 长期模式：与近期日记对照，说明哪些倾向是重复出现的，哪些只是今天的偶发现象；没有足够证据时明确说证据不足。
7. 未完成事项：列出仍悬而未决的承诺、问题和需要继续观察的线索。
8. 下一步：给出明天可以执行的 1—3 个小行动，说明优先级和判断依据。
9. 长期记忆更新候选：整理“稳定事实 / 正在形成的偏好或模式 / 需要继续验证的假设 / 已失效或应修正的旧判断”。这部分只是供我的个人复盘系统迭代使用，不要声称已经写入永久记忆。

引用日记时只做短句摘录，并标明对应记录片或时间。不要把猜测写成事实，不要为了完整而填补日记中没有的信息。最后提出 2—4 个真正值得我继续思考的问题。`
}
